    private static void named(String name, AspectList aspects) { tag(GameRegistry.findItem("mbo", name), aspects); }
    private static void tag(Object value, AspectList aspects) {
        if (value instanceof Object[]) {
            for (Object entry : (Object[]) value) tag(entry, aspects);
        } else tagMeta(value, OreDictionary.WILDCARD_VALUE, aspects);
    }
    private static void tagMeta(Object value, int metadata, AspectList aspects) {
        Item item = value instanceof Block ? Item.getItemFromBlock((Block) value)
                : value instanceof Item ? (Item) value : null;
        if (item != null) ThaumcraftApi.registerObjectTag(new ItemStack(item, 1, metadata), aspects.copy());
    }
    private static AspectList a(Object... pairs) {
        AspectList aspects = new AspectList();
        for (int i = 0; i < pairs.length; i += 2) aspects.add((Aspect) pairs[i], (Integer) pairs[i + 1]);
        return aspects;
    }
